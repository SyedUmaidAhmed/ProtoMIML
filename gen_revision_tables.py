# ── Table: validation protocol and thresholds ──────────────────────────────
def table_validation():
    rows = []
    facts['validation'] = {}
    for ds, name in DS:
        sub = json.load(open(os.path.join('results', f'incremental_{ds}_10folds.json')))[ds]
        std = pol(f'protomiml_standard_{ds}')
        t05 = pol(f'protomiml_standard_{ds}', 'selected_t05')
        cv = pol(f'protomiml_cvens_{ds}')
        val_n = summary(f'protomiml_standard_{ds}')['fold_info'][0]['val_size']
        ps = {m: paired_p(folds(f'protomiml_cvens_{ds}', m), folds(f'protomiml_standard_{ds}', m))
              for m in M}
        facts['validation'][ds] = {'val_bags': val_n,
                                   'submitted': {m: sub[m][0] for m in M},
                                   'standard': {m: std[m]['mean'] for m in M},
                                   'standard_t05_HL': t05['HammingLoss']['mean'],
                                   'cvens': {m: cv[m]['mean'] for m in M}, 'p_cvens_vs_standard': ps}

        def mk(m):
            if ps[m] >= ALPHA:
                return ''
            return r'$^{\dagger}$' if better(cv[m]['mean'], std[m]['mean'], m) else r'$^{\ddagger}$'
        rows.append(rf'\multirow{{3}}{{*}}{{{name} ({val_n})}} & submitted (90/10, MPS) & '
                    + ' & '.join(f3(sub[m][0]) for m in M) + r' & -- \\')
