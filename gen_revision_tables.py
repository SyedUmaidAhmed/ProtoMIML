# ── helpers ──────────────────────────────────────────────────────────────────
def r3(x, nd=3):
    """Round half-up (not banker's) so that displayed ties are unambiguous."""
    q = Decimal(1).scaleb(-nd)
    return float(Decimal(repr(round(float(x), 10))).quantize(q, rounding=ROUND_HALF_UP))


def f3(x, nd=3):
    return f'{r3(x, nd):.{nd}f}'


def summary(tag):
    return json.load(open(os.path.join(REV, f'summary_{tag}.json')))


def pol(tag, policy='selected'):
    return summary(tag)['policies'][policy]


def folds(tag, metric, policy='selected'):
    return np.array(pol(tag, policy)[metric]['per_fold'])


def classical(ds, holdout=False):
    d = json.load(open(os.path.join(REV, f'classical_{ds}{"_holdout" if holdout else ""}.json')))
    return {k: {m: np.array([f[m] for f in d[k]['per_fold']]) for m in M} for k, _ in CLASSICAL}


def paired_p(x, y):
    return float(wilcoxon(x, y).pvalue) if np.any(x != y) else 1.0


def better(a, b, m):
    return a < b if m in LOWER else a > b


def best_of(values, m):
    return min(values) if m in LOWER else max(values)


def cell(v, bold=False, sd=None, mark=''):
    s = f3(v)
    if bold:
        s = rf'\textbf{{{s}}}'
    if mark:
        s += mark
    if sd is not None:
        s += rf'{{\scriptsize$\pm${f3(sd)}}}'
    return s


def write(name, body):
    path = os.path.join(OUT, name)
    open(path, 'w').write(HEADER + body)
    print('wrote', path)


