#!/usr/bin/env python3
"""figures/gate_strip.tex — every learned gate value, one dot each.

Strip plot of all per-label fold-averaged gate values sigma(g_l) from
results/gate_values.json.  Visualizes the inert-gate negative result:
80 labels across four datasets, all hugging the 0.5 initialization.
"""
import json
d = json.load(open('results/gate_values.json'))
ORDER = [('scene','Scene'), ('letter_carroll','Carroll'),
         ('letter_frost','Frost'), ('MSCV2','MSCV2')]
lines = [r"""% AUTO-GENERATED by gen_gate_strip.py -- do not edit by hand.
\begin{figure}[!htb]
\centering
\resizebox{0.85\linewidth}{!}{%
\begin{tikzpicture}
\definecolor{oiBlue}{RGB}{0,114,178}
\begin{axis}[
  width=13cm, height=5.6cm,
  ylabel={learned gate $\sigma(g_l)$},
  xtick={1,2,3,4}, xticklabels={Scene (5), Carroll (26), Frost (26), MSCV2 (23)},
  xmin=0.5, xmax=4.5, ymin=0.40, ymax=0.62,
  axis lines=left, ymajorgrids, grid style={gray!18},
  tick label style={font=\small}, label style={font=\small}, clip=false,
]
\addplot[gray, dashed, thick, sharp plot, forget plot] coordinates {(0.5,0.5) (4.5,0.5)};
\node[font=\scriptsize, text=gray, anchor=west] at (axis cs:4.5,0.5) {init $=0.5$};
\node[font=\scriptsize, text=gray, anchor=west] at (axis cs:0.55,0.60) {parametric-leaning $\uparrow$};
\node[font=\scriptsize, text=gray, anchor=west] at (axis cs:0.55,0.42) {prototype-leaning $\downarrow$};"""]
for i,(ds,name) in enumerate(ORDER, start=1):
    gates = d[ds]['mean_gates']
    n = len(gates)
    pts = ' '.join(f'({i + (j-(n-1)/2)*(0.7/max(n-1,1)):.3f},{g:.4f})' for j,g in enumerate(sorted(gates)))
    lines.append(rf"\addplot[only marks, mark=*, mark size=1.7pt, color=oiBlue, opacity=0.75, forget plot] coordinates {{{pts}}};")
lines.append(r"""\end{axis}
\end{tikzpicture}%
}
\caption{Every learned fusion gate in the study, one dot per label (fold-averaged,
80 labels across four datasets; values from the archived \texttt{gate\_values.json}).
The full training pipeline is free to move each gate anywhere in $(0,1)$, yet every
gate ends within five points of the $0.5$ initialization and within two points of its
dataset's other labels---the inert-gate negative result of Section~\ref{sec:gate_analysis},
confirmed causally by the \textsc{fixed gate} ablation of Table~\ref{tab:ablation}.}
\label{fig:gate_strip}
\end{figure}
""")
open('paper_kais/figures/gate_strip.tex','w').write('\n'.join(lines))
print("gate_strip.tex written")
