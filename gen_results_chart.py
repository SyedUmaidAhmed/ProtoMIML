#!/usr/bin/env python3
"""figures/results_overview.tex — the paper's evidence at a glance.

Dot-ladder of Average Precision per dataset for four predictors:
best published baseline, ABMIL (shared), ABMIL (per-label), ProtoMIML.
Values come from results/*.json plus Table 4's published-record maxima.
Okabe-Ito colorblind-safe hues, fixed series order.
"""
import json

DS = [('scene','Scene'), ('reuters','Reuters'), ('letter_carroll','Carroll'),
      ('letter_frost','Frost'), ('MSCV2','MSCV2')]
BEST_PUB = {'scene':0.783,'reuters':0.965,'letter_carroll':0.715,
            'letter_frost':0.704,'MSCV2':0.688}   # best AP per dataset, Table 4

series = []
pub = [(i+1, BEST_PUB[ds]) for i,(ds,_) in enumerate(DS)]
sh  = [(i+1, json.load(open(f'results/baseline_abmil_{ds}_10folds.json'))['AveragePrecision']['mean']) for i,(ds,_) in enumerate(DS)]
pl  = [(i+1, json.load(open(f'results/baseline_abmil_per_label_{ds}_10folds.json'))['AveragePrecision']['mean']) for i,(ds,_) in enumerate(DS)]
pm  = [(i+1, json.load(open(f'results/incremental_{ds}_10folds.json'))[ds]['AveragePrecision'][0]) for i,(ds,_) in enumerate(DS)]

def coords(pts, off=0.0):
    return ' '.join(f'({x+off:.2f},{y:.4f})' for x,y in pts)

lines = [r"""% AUTO-GENERATED by gen_results_chart.py -- do not edit by hand.
\begin{figure}[!htb]
\centering
\resizebox{0.92\linewidth}{!}{%
\begin{tikzpicture}
\definecolor{oiGray}{RGB}{130,130,130}\definecolor{oiSky}{RGB}{86,180,233}
\definecolor{oiOrange}{RGB}{230,159,0}\definecolor{oiBlue}{RGB}{0,114,178}
\begin{axis}[
  width=14.5cm, height=8cm,
  ylabel={Average Precision},
  xtick={1,2,3,4,5}, xticklabels={Scene, Reuters, Carroll, Frost, MSCV2},
  xmin=0.5, xmax=5.6, ymin=0.58, ymax=1.0,
  axis lines=left, ymajorgrids, grid style={gray!18},
  legend style={at={(0.5,-0.13)}, anchor=north, legend columns=4, draw=none,
                font=\scriptsize, /tikz/every even column/.append style={column sep=8pt}},
  tick label style={font=\small}, label style={font=\small},
  clip=false,
]"""]
# light connector per dataset from worst to best, drawn first (recessive)
for i,(ds,_) in enumerate(DS):
    ys = [BEST_PUB[ds], sh[i][1], pl[i][1], pm[i][1]]
    lines.append(rf"\draw[gray!35, line width=1pt] (axis cs:{i+1},{min(ys):.4f}) -- (axis cs:{i+1},{max(ys):.4f});")
for name, pts, color, mark in [
    ('Best published baseline', pub, 'oiGray',  'square*'),
    ('ABMIL (shared)',          sh,  'oiSky',   '*'),
    ('ABMIL (per-label)',       pl,  'oiOrange','*'),
    ('ProtoMIML (ours)',        pm,  'oiBlue',  'diamond*')]:
    lines.append(rf"\addplot[only marks, mark={mark}, mark size=3.1pt, color={color}] coordinates {{{coords(pts)}}};")
    lines.append(rf"\addlegendentry{{{name}}}")
# direct labels on ProtoMIML
for (x,y) in pm:
    lines.append(rf"\node[font=\scriptsize\bfseries, text=oiBlue, anchor=south] at (axis cs:{x},{y+0.008:.4f}) {{{y:.3f}}};")
lines.append(r"""\end{axis}
\end{tikzpicture}%
}
\caption{The evidence at a glance: Average Precision on all five benchmarks for the best
published baseline (Table~\ref{tab:comprehensive}), the two split-matched attention-MIL
baselines trained on identical folds (Section~\ref{sec:neural_baselines}), and ProtoMIML.
ProtoMIML is best on every dataset.  The step from shared to per-label attention closes
most of the gap on Carroll and Frost, and ProtoMIML's remaining architecture and training
recipe supply the consistent residual---the decomposition discussed in
Section~\ref{sec:neural_baselines}.  Published baselines are not split-matched
(Section~\ref{sec:protocol_caveat}); the ABMIL comparisons are.}
\label{fig:results_overview}
\end{figure}
""")
open('paper_kais/figures/results_overview.tex','w').write('\n'.join(lines))
print("results_overview.tex written")
