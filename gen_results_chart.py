#!/usr/bin/env python3
"""figures/results_overview.tex — the paper's evidence at a glance.

Dot plot of Average Precision per dataset for six predictors: best published
baseline, best re-run classical method (our folds), ABMIL shared and per-label
(ProtoMIML's full recipe), ProtoMIML (standard) and ProtoMIML (CV ensemble).
Values come from results/revision/*.json plus the published-record maxima.
Okabe-Ito colorblind-safe hues, fixed series order.
"""
import json

DS = [('scene','Scene'), ('reuters','Reuters'), ('letter_carroll','Carroll'),
      ('letter_frost','Frost'), ('MSCV2','MSCV2')]
BEST_PUB = {'scene':0.783,'reuters':0.965,'letter_carroll':0.715,
            'letter_frost':0.704,'MSCV2':0.688}   # best AP per dataset, Table 4

REV = 'results/revision'
def ap(tag, policy='selected'):
    return json.load(open(f'{REV}/summary_{tag}.json'))['policies'][policy]['AveragePrecision']['mean']
def best_classical(ds):
    d = json.load(open(f'{REV}/classical_{ds}.json'))
    return max(sum(f['AveragePrecision'] for f in d[k]['per_fold']) / len(d[k]['per_fold']) for k in d)

pub = [(i+1, BEST_PUB[ds]) for i,(ds,_) in enumerate(DS)]
cl  = [(i+1, best_classical(ds)) for i,(ds,_) in enumerate(DS)]
sh  = [(i+1, ap(f'abmil_standard_{ds}')) for i,(ds,_) in enumerate(DS)]
pl  = [(i+1, ap(f'abmil_per_label_standard_{ds}')) for i,(ds,_) in enumerate(DS)]
st  = [(i+1, ap(f'protomiml_standard_{ds}')) for i,(ds,_) in enumerate(DS)]
pm  = [(i+1, ap(f'protomiml_cvens_{ds}')) for i,(ds,_) in enumerate(DS)]

def coords(pts, off=0.0):
    return ' '.join(f'({x+off:.2f},{y:.4f})' for x,y in pts)

lines = [r"""% AUTO-GENERATED by gen_results_chart.py -- do not edit by hand.
\begin{figure}[!htb]
\centering
\resizebox{0.92\linewidth}{!}{%
\begin{tikzpicture}
\definecolor{oiGray}{RGB}{130,130,130}\definecolor{oiSky}{RGB}{86,180,233}
\definecolor{oiOrange}{RGB}{230,159,0}\definecolor{oiBlue}{RGB}{0,114,178}\definecolor{oiGreen}{RGB}{0,158,115}
\begin{axis}[
  width=14.5cm, height=8cm,
  ylabel={Average Precision},
  xtick={1,2,3,4,5}, xticklabels={Scene, Reuters, Carroll, Frost, MSCV2},
  xmin=0.5, xmax=5.6, ymin=0.58, ymax=1.0,
  axis lines=left, ymajorgrids, grid style={gray!18},
  legend style={at={(0.5,-0.13)}, anchor=north, legend columns=3, draw=none,
                font=\scriptsize, /tikz/every even column/.append style={column sep=8pt}},
  tick label style={font=\small}, label style={font=\small},
  clip=false,
]"""]
for name, pts, color, mark, off in [
    ('Best published',                   pub, 'oiGray',   'square*',  -0.25),
    ('Best classical, our folds',        cl,  'oiGreen',  'triangle*',-0.15),
    ('ABMIL (shared), same recipe',      sh,  'oiSky',    '*',        -0.05),
    ('ABMIL (per-label), same recipe',   pl,  'oiOrange', '*',         0.05),
    ('ProtoMIML, standard protocol',     st,  'oiBlue',   'diamond',   0.15),
    ('ProtoMIML, CV ensemble',           pm,  'oiBlue',   'diamond*',  0.25)]:
    lines.append(rf"\addplot[only marks, mark={mark}, mark size=3.1pt, color={color}] coordinates {{{coords(pts, off)}}};")
    lines.append(rf"\addlegendentry{{{name}}}")
# direct labels on ProtoMIML
for (x,y) in pm:
    lines.append(rf"\node[font=\scriptsize\bfseries, text=oiBlue, anchor=south] at (axis cs:{x+0.25},{y+0.008:.4f}) {{{y:.3f}}};")
lines.append(r"""\end{axis}
\end{tikzpicture}%
}
\caption{Average Precision on the five benchmarks.  From left to right within each dataset:
the best published baseline (Table~\ref{tab:comprehensive}; other partitions or a smaller training set),
the strongest classical method re-run on our folds (Table~\ref{tab:classical_matched}),
the two attention-MIL baselines trained with ProtoMIML's full recipe (Table~\ref{tab:controlled}),
and ProtoMIML under the standard and the cross-validated-ensemble protocols (labelled).
All entries except the published ones are computed on identical folds.}
\label{fig:results_overview}
\end{figure}
""")
open('paper_kais/figures/results_overview.tex','w').write('\n'.join(lines))
print("results_overview.tex written")
