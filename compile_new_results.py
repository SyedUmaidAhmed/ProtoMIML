#!/usr/bin/env python3
"""Regenerate the ablation and neural-baseline LaTeX tables from results JSON.

Emits:
  paper_kais/sections/ablation_table_generated.tex   -- ablation incl. matched
                                                        control + fixed gate
  paper_kais/sections/neural_baselines_table.tex     -- ABMIL comparison

Both read only from results/*.json, so the tables cannot drift from the runs.
Missing runs are rendered as "--" rather than silently omitted, so an
incomplete sweep is visible in the compiled PDF.

    python compile_new_results.py
"""
import json
import os

RESULTS = 'results'
OUT = 'paper_kais/sections'

DATASETS = [('scene', 'Scene'), ('reuters', 'Reuters'),
            ('letter_carroll', 'Carroll'), ('letter_frost', 'Frost'),
            ('MSCV2', 'MSCV2')]

# (variant key, printed label) -- 'full' is the matched control and must be first
ABLATION_ROWS = [
    ('full',            r'\textbf{Full ProtoMIML} (matched control)'),
    ('fixed_gate',      r'Fixed gate $\sigma(g_l){=}0.5$'),
    ('no_sam',          r'w/o SAM (plain AdamW)'),
    ('no_isab',         r'w/o ISAB'),
    ('no_gcn',          r'w/o GCN'),
    ('no_prototypes',   r'w/o Prototypes'),
    ('no_consistency',  r'w/o Consistency'),
    ('no_mixup',        r'w/o Mixup$^\dagger$'),
]

# Metric shown per dataset in the ablation table, matching the existing paper
ABLATION_METRIC = {
    'scene': ('AveragePrecision', 'HammingLoss'),
    'reuters': ('AveragePrecision', 'HammingLoss'),
    'letter_carroll': ('AveragePrecision', 'RankingLoss'),
    'letter_frost': ('AveragePrecision', 'RankingLoss'),
    'MSCV2': ('AveragePrecision', 'HammingLoss'),
}

METRICS = [('HammingLoss', r'HL$\downarrow$'), ('OneError', r'OE$\downarrow$'),
           ('Coverage', r'Cov$\downarrow$'), ('RankingLoss', r'RL$\downarrow$'),
           ('AveragePrecision', r'AP$\uparrow$')]


def load(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def val(blob, metric):
    """Return (mean, std) or None. Handles both JSON shapes in results/."""
    if blob is None or metric not in blob:
        return None
    v = blob[metric]
    if isinstance(v, dict):                 # ablation/baseline shape
        return v.get('mean'), v.get('std')
    if isinstance(v, (list, tuple)):        # incremental shape: [mean, std]
        return (float(v[0]), float(v[1]) if len(v) > 1 else None)
    return float(v), None


def fmt(pair, dec=4):
    if pair is None or pair[0] is None:
        return '--'
    from decimal import Decimal, ROUND_HALF_UP
    q = Decimal(1).scaleb(-dec)
    return str(Decimal(repr(pair[0])).quantize(q, rounding=ROUND_HALF_UP))


def build_ablation_table():
    rows = []
    for key, label in ABLATION_ROWS:
        cells = []
        for ds, _ in DATASETS:
            blob = load(f'{RESULTS}/ablation_{key}_{ds}_5folds.json')
            if key == 'no_mixup' and ds != 'scene':
                cells.append(r'\multicolumn{2}{c|}{N/A}' if ds != 'MSCV2'
                             else r'\multicolumn{2}{c}{N/A}')
                continue
            m1, m2 = ABLATION_METRIC[ds]
            cells.append(f'{fmt(val(blob, m1))} & {fmt(val(blob, m2))}')
        rows.append(f'{label} & ' + ' & '.join(cells) + r' \\')

    header = ' & '.join(
        rf'\multicolumn{{2}}{{c{"|" if i < len(DATASETS) - 1 else ""}}}{{{name}}}'
        for i, (_, name) in enumerate(DATASETS))
    submetrics = []
    for ds, _ in DATASETS:
        m1, m2 = ABLATION_METRIC[ds]
        short = {'AveragePrecision': r'AP$\uparrow$', 'HammingLoss': r'HL$\downarrow$',
                 'RankingLoss': r'RL$\downarrow$'}
        submetrics.append(f'{short[m1]} & {short[m2]}')

    body = '\n'.join(rows[:1]) + '\n\\midrule\n' + '\n'.join(rows[1:])
    return rf"""% AUTO-GENERATED by compile_new_results.py -- do not edit by hand.
\begin{{table}}[!htb]
\centering
\caption{{Ablation study (5-fold CV, single seed, no ensemble).  \textbf{{Every row
including the full model is run under this identical protocol}}, so each delta
isolates the removed component rather than conflating it with the 10-fold
5-seed ensemble used for the headline results in Table~\ref{{tab:comprehensive}}.
$\dagger$~Mixup applies only to Scene (fixed bag size).
Two rows match the control at reported precision for verifiable reasons:
the consistency loss activates only after Phase-2 epoch 80, which early stopping
never reached on any Frost fold (stops at epochs 37--71), and on Reuters the
frozen gate is irrelevant in the four of five folds where validation selected
the parametric-only pathway, while the near-uniform learned gate coincides with
the frozen $0.5$ in the remaining fold.}}
\label{{tab:ablation}}
\resizebox{{\linewidth}}{{!}}{{%
\begin{{tabular}}{{l|cc|cc|cc|cc|cc}}
\toprule
\multirow{{2}}{{*}}{{Variant}} & {header} \\
& {' & '.join(submetrics)} \\
\midrule
{body}
\bottomrule
\end{{tabular}}%
}}
\end{{table}}
"""


def build_baseline_table():
    rows = []
    model_labels = [('abmil', 'ABMIL (shared attention)'),
                    ('abmil_per_label', 'ABMIL (per-label attention)')]
    for ds, name in DATASETS:
        first = True
        for mkey, mlabel in model_labels:
            blob = load(f'{RESULTS}/baseline_{mkey}_{ds}_10folds.json')
            cells = ' & '.join(fmt(val(blob, m), 3) for m, _ in METRICS)
            prefix = rf'\multirow{{3}}{{*}}{{{name}}}' if first else ''
            rows.append(f'{prefix} & {mlabel} & {cells} ' + r'\\')
            first = False
        proto = load(f'{RESULTS}/incremental_{ds}_10folds.json')
        pb = proto.get(ds) if proto else None
        cells = ' & '.join(fmt(val(pb, m), 3) for m, _ in METRICS)
        rows.append(r' & \textbf{ProtoMIML (ours)} & ' + cells + r' \\')
        rows.append(r'\midrule')
    if rows and rows[-1] == r'\midrule':
        rows.pop()

    return rf"""% AUTO-GENERATED by compile_new_results.py -- do not edit by hand.
\begin{{table}}[!htb]
\centering
\small
\caption{{Split-matched comparison against attention-based MIL baselines.
All three methods are trained and evaluated on \emph{{identical}} folds with
identical normalisation, validation carve-out and threshold optimisation; the
only difference is the model.  Unlike Table~\ref{{tab:comprehensive}}, this is a
paired comparison.  Coverage is raw depth count.}}
\label{{tab:neural_baselines}}
\resizebox{{\linewidth}}{{!}}{{%
\begin{{tabular}}{{@{{}}llccccc@{{}}}}
\toprule
Dataset & Method & {' & '.join(lbl for _, lbl in METRICS)} \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}%
}}
\end{{table}}
"""


def main():
    os.makedirs(OUT, exist_ok=True)
    for fname, builder in [('ablation_table_generated.tex', build_ablation_table),
                           ('neural_baselines_table.tex', build_baseline_table)]:
        path = os.path.join(OUT, fname)
        with open(path, 'w') as f:
            f.write(builder())
        print(f'wrote {path}')

    missing = []
    for key, _ in ABLATION_ROWS:
        for ds, _ in DATASETS:
            if key == 'no_mixup' and ds != 'scene':
                continue
            p = f'{RESULTS}/ablation_{key}_{ds}_5folds.json'
            if not os.path.exists(p):
                missing.append(p)
    for mkey in ('abmil', 'abmil_per_label'):
        for ds, _ in DATASETS:
            p = f'{RESULTS}/baseline_{mkey}_{ds}_10folds.json'
            if not os.path.exists(p):
                missing.append(p)
    if missing:
        print(f'\n{len(missing)} run(s) still missing (rendered as "--"):')
        for m in missing:
            print(f'  {m}')
    else:
        print('\nAll runs present.')


if __name__ == '__main__':
    main()
