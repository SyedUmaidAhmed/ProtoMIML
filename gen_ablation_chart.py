#!/usr/bin/env python3
"""Regenerate figures/ablation_chart.tex from the matched-control JSONs.

Dot plot of Delta AP (variant minus matched control, in AP points) per dataset,
with a shaded band showing +/- 1 fold standard deviation of the control run.
Every value comes from results/*.json; nothing is hand-entered.
"""
import json

DS = [('scene','Scene'), ('reuters','Reuters'), ('letter_carroll','Carroll'),
      ('letter_frost','Frost'), ('MSCV2','MSCV2')]
VARS = [('fixed_gate','Fixed gate','ablBlue'), ('no_sam','w/o SAM','ablGray'),
        ('no_isab','w/o ISAB','ablRed'),
        ('no_gcn','w/o GCN','ablOrange'), ('no_prototypes','w/o Prototypes','ablPurple'),
        ('no_consistency','w/o Consistency','ablTeal')]

def load(v, ds):
    try:
        return json.load(open(f'results/ablation_{v}_{ds}_5folds.json'))
    except FileNotFoundError:
        return None

full = {ds: load('full', ds) for ds, _ in DS}

lines = [r"""% AUTO-GENERATED by gen_ablation_chart.py -- do not edit by hand.
\begin{figure}[!htb]
\centering
\resizebox{0.95\linewidth}{!}{%
\begin{tikzpicture}
\definecolor{ablBlue}{RGB}{31,119,180}\definecolor{ablRed}{RGB}{214,39,40}
\definecolor{ablOrange}{RGB}{255,127,14}\definecolor{ablPurple}{RGB}{148,103,189}
\definecolor{ablTeal}{RGB}{23,145,135}\definecolor{ablGray}{RGB}{99,99,99}
\begin{axis}[
  width=15cm, height=7.2cm,
  ylabel={$\Delta$ AP vs.\ matched control (points)},
  xtick={1,2,3,4,5},
  xticklabels={Scene, Reuters, Carroll, Frost, MSCV2},
  xmin=0.5, xmax=5.5,
  ymin=-5.2, ymax=5.2,
  axis lines=left, ymajorgrids, grid style={gray!20},
  legend style={at={(0.5,-0.14)}, anchor=north, legend columns=6,
                draw=none, font=\scriptsize, /tikz/every even column/.append style={column sep=6pt}},
  tick label style={font=\small}, label style={font=\small},
]"""]

# Shaded +/- fold-std band of the control, per dataset
for i, (ds, _) in enumerate(DS, start=1):
    sd = full[ds]['AveragePrecision']['std'] * 100
    lines.append(
        rf"\fill[gray!18] (axis cs:{i-0.38},{-sd:.2f}) rectangle (axis cs:{i+0.38},{sd:.2f});")
lines.append(r"\addplot[black, thick, sharp plot, update limits=false, forget plot] coordinates {(0.5,0) (5.5,0)};")

offs = [-0.30, -0.18, -0.06, 0.06, 0.18, 0.30]
for (v, name, color), off in zip(VARS, offs):
    pts = []
    for i, (ds, _) in enumerate(DS, start=1):
        blob = load(v, ds)
        if blob is None:
            continue
        d = (blob['AveragePrecision']['mean'] - full[ds]['AveragePrecision']['mean']) * 100
        pts.append(f"({i+off:.2f},{d:.2f})")
    lines.append(
        rf"\addplot[only marks, mark=*, mark size=2.4pt, color={color}] coordinates {{{' '.join(pts)}}};")
    lines.append(rf"\addlegendentry{{{name}}}")

lines.append(r"""\end{axis}
\end{tikzpicture}%
}
\caption{Ablation deltas under the matched protocol (5-fold CV, single seed): change in
Average Precision when one component is removed (or the fusion gate is frozen at $0.5$),
relative to the full model run under the \emph{identical} protocol.  Shaded bands show
$\pm 1$ fold standard deviation of the matched control on each dataset.  No variant
leaves its dataset's noise band, visualising the negative result of
Section~\ref{sec:component_analysis}: individual component contributions are not
resolvable at this dataset scale.}
\label{fig:ablation_chart}
\end{figure}
""")
open('paper_kais/figures/ablation_chart.tex','w').write('\n'.join(lines))
print("figures/ablation_chart.tex regenerated from JSONs")
