#!/usr/bin/env python3
"""Generate figures/measured_attention.tex from results/attention_scene_fold0.json.

Real cross-attention weights from a trained Scene fold-0 model, two test bags.
Nothing is stylized: cell intensity is the measured weight.
"""
import json

d = json.load(open('results/attention_scene_fold0.json'))
L = d['label_names']
BAGS = [0, 3]  # both multi-label, both predicted fully correctly
CW, CH = 0.72, 0.52  # cell size cm

def panel(bag, ox):
    A, probs, true = bag['attention'], bag['probs'], bag['true_labels']
    out = []
    vmax = max(max(r) for r in A)
    for r, row in enumerate(A):
        for c, w in enumerate(row):
            shade = int(round(88 * w / vmax))
            out.append(rf"\fill[attnBlue!{shade}] ({ox+c*CW:.2f},{-r*CH:.2f}) rectangle ({ox+(c+1)*CW:.2f},{-(r+1)*CH:.2f});")
            out.append(rf"\node[font=\tiny] at ({ox+(c+0.5)*CW:.2f},{-(r+0.5)*CH:.2f}) {{{w:.2f}}};")
    for c in range(9):
        out.append(rf"\node[font=\scriptsize] at ({ox+(c+0.5)*CW:.2f},{0.3:.2f}) {{$x_{{{c+1}}}$}};")
    for r, name in enumerate(L):
        marker = r'$\bullet$\,' if true[r] else ''
        style = r'\bfseries ' if true[r] else ''
        out.append(rf"\node[font=\scriptsize, anchor=east] at ({ox-0.12:.2f},{-(r+0.5)*CH:.2f}) {{{style}{marker}{name}}};")
        out.append(rf"\node[font=\scriptsize, anchor=west] at ({ox+9*CW+0.12:.2f},{-(r+0.5)*CH:.2f}) {{{probs[r]:.2f}}};")
    out.append(rf"\node[font=\scriptsize, anchor=west] at ({ox+9*CW+0.12:.2f},{0.3:.2f}) {{$\hat{{p}}_l$}};")
    return out

lines = [r"""% AUTO-GENERATED by gen_attention_figure.py -- measured values, do not edit.
\begin{figure}[!htb]
\centering
\resizebox{\linewidth}{!}{%
\begin{tikzpicture}
\definecolor{attnBlue}{RGB}{31,119,180}"""]
lines += panel(d['bags'][BAGS[0]], 0.0)
lines += panel(d['bags'][BAGS[1]], 9*CW + 3.2)
lines.append(r"""\end{tikzpicture}%
}
\caption{\textbf{Measured} cross-attention weights $\alpha \in \mathbb{R}^{L \times 9}$ from a
trained Scene fold-0 model on two correctly-predicted multi-label test bags
(left: true labels \emph{sea, trees}; right: \emph{sea, sunset}; $\bullet$ marks true labels,
right column gives predicted probabilities, thresholds are per-label).  The distributions are
soft---mean row entropy $2.08$ against $\ln 9 = 2.20$ for uniform---but label-differentiated:
across the six bags we recorded, the five label queries place their attention maxima on three
to five distinct instances per bag.}
\label{fig:measured_attention}
\end{figure}
""")
open('paper_kais/figures/measured_attention.tex','w').write('\n'.join(lines))
print("figures/measured_attention.tex written")
